using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace ClosedValues
{
    /// <summary>
    /// Writes the generated partial class, record or struct for one closed value type.
    /// </summary>
    internal sealed class ClosedValueSourceWriter(ClosedValueModel model)
    {
        private readonly StringBuilder builder = new();

        private int indentation;

        private string Type => Identifier(model.TypeName);

        private string Nullable => model.SupportsNullable ? "?" : string.Empty;

        /// <summary>The annotation for a variable of this type that may hold no instance; a struct always holds one.</summary>
        private string InstanceNullable => model.IsValueType ? string.Empty : Nullable;

        private string Keyword => (model.IsRecord, model.IsValueType) switch
        {
            (true, true) => "record struct",
            (true, false) => "record",
            (false, true) => "struct",
            (false, false) => "class",
        };

        /// <summary>The key that TryParse, Parse, the conversions and the converters use, or null.</summary>
        private ClosedValueMember? KeyMember => model.Members.FirstOrDefault(member => member.IsKey);

        /// <summary>The key when it can order the instances, or null.</summary>
        private ClosedValueMember? OrderMember => KeyMember is { IsOrdered: true } member ? member : null;

        private string NotNullWhenTrue => model.SupportsNullable && model.HasNotNullWhenAttribute && !model.IsValueType
            ? "[global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] "
            : string.Empty;

        private string Bang => model.SupportsNullable ? "!" : string.Empty;

        private string NoInstance => model.IsValueType ? "default" : "null";

        public string Write()
        {
            AppendLine("// <auto-generated/>");
            if (model.SupportsNullable)
            {
                AppendLine("#nullable enable");
            }

            AppendLine();
            bool hasNamespace = model.Namespace.Length > 0;
            if (hasNamespace)
            {
                AppendLine($"namespace {model.Namespace}");
                OpenBlock();
            }

            if (model.WritesTypeConverterAttribute)
            {
                AppendLine($"[global::System.ComponentModel.TypeConverter(typeof({Type}.ClosedValueTypeConverter))]");
            }

            if (model.WritesJsonConverterAttribute)
            {
                AppendLine($"[global::System.Text.Json.Serialization.JsonConverter(typeof({Type}.ClosedValueJsonConverter))]");
            }

            AppendLine($"partial {Keyword} {Type}{BaseList()}");
            OpenBlock();
            WriteConstructor();
            WriteAll();
            WriteFromName();
            WriteTryParse();
            WriteMatch();
            WriteSwitch();
            WriteMap();
            WriteMatchWithState();
            WriteEquality();
            WriteComparison();
            WriteConversions();
            WriteToString();
            WriteTypeConverter();
            WriteJsonConverter();
            WriteParsable();
            CloseBlock();

            if (hasNamespace)
            {
                CloseBlock();
            }

            return builder.ToString();
        }

        private void WriteConstructor()
        {
            if (model.IsValueType && model.Members.Count == 0)
            {
                // A struct cannot declare a private parameterless constructor; new() already gives the only value.
                return;
            }

            string parameters = string.Join(", ", model.Members.Select(member => $"{member.Type} {Parameter(member.Name)}"));
            string references = string.Join(", ", model.Members.Select(member => $"ref {member.Type} {Parameter(member.Name)}"));
            string arguments = string.Join(", ", model.Members.Select(member => $"ref {Parameter(member.Name)}"));

            AppendLine("/// <summary>Implement this partial method to check or change the arguments of every instance. Without a body, the call compiles away.</summary>");
            AppendLine($"static partial void {ClosedValueNames.ValidationMethodName}({references});");
            AppendLine();
            AppendLine($"private {Type}({parameters})");
            OpenBlock();
            AppendLine($"{ClosedValueNames.ValidationMethodName}({arguments});");
            foreach (ClosedValueMember member in model.Members)
            {
                AppendLine($"this.{Identifier(member.Name)} = {Parameter(member.Name)};");
            }

            CloseBlock();
            AppendLine();
        }

        private void WriteAll()
        {
            string instances = string.Join(", ", model.Instances.Select(Identifier));
            AppendLine($"private static {Type}[]{Nullable} allInstances;");
            AppendLine();
            AppendLine("/// <summary>Returns every instance of this closed value, in declaration order.</summary>");
            AppendLine($"public static global::System.Collections.Generic.IReadOnlyList<{Type}> All => allInstances ?? (allInstances = new {Type}[] {{ {instances} }});");
            AppendLine();
        }

        private string ParseValueType(ClosedValueMember member) =>
            member.IsString ? member.Type.TrimEnd('?') + Nullable : member.Type;

        private void WriteFromName()
        {
            string result = $"{NotNullWhenTrue}out {Type}{InstanceNullable} result";

            AppendLine("/// <summary>Finds the instance with the name <paramref name=\"name\"/>, compared ordinally.</summary>");
            AppendLine($"public static bool TryFromName(string{Nullable} name, {result}) => TryFromName(name, global::System.StringComparison.Ordinal, out result);");
            AppendLine();

            AppendLine("/// <summary>Finds the instance with the name <paramref name=\"name\"/>, compared with <paramref name=\"comparison\"/>.</summary>");
            AppendLine($"public static bool TryFromName(string{Nullable} name, global::System.StringComparison comparison, {result})");
            OpenBlock();
            if (model.Instances.Count > 0)
            {
                AppendLine("if (comparison == global::System.StringComparison.Ordinal)");
                OpenBlock();
                AppendLine("switch (name)");
                OpenBlock();
                foreach (string instance in model.Instances)
                {
                    AppendLine($"case \"{instance}\":");
                    AppendLine($"    result = {Identifier(instance)};");
                    AppendLine("    return true;");
                }

                CloseBlock();
                AppendLine();
                AppendLine($"result = {NoInstance};");
                AppendLine("return false;");
                CloseBlock();
                AppendLine();
            }

            foreach (string instance in model.Instances)
            {
                AppendLine($"if (string.Equals(name, \"{instance}\", comparison))");
                OpenBlock();
                AppendLine($"result = {Identifier(instance)};");
                AppendLine("return true;");
                CloseBlock();
                AppendLine();
            }

            AppendLine($"result = {NoInstance};");
            AppendLine("return false;");
            CloseBlock();
            AppendLine();

            AppendLine("/// <summary>Returns the instance with the name <paramref name=\"name\"/>, compared ordinally.</summary>");
            AppendLine("/// <exception cref=\"global::System.ArgumentException\">No instance has the name.</exception>");
            AppendLine($"public static {Type} FromName(string name) => FromName(name, global::System.StringComparison.Ordinal);");
            AppendLine();

            AppendLine("/// <summary>Returns the instance with the name <paramref name=\"name\"/>, compared with <paramref name=\"comparison\"/>.</summary>");
            AppendLine("/// <exception cref=\"global::System.ArgumentException\">No instance has the name.</exception>");
            AppendLine($"public static {Type} FromName(string name, global::System.StringComparison comparison)");
            OpenBlock();
            AppendLine($"if (TryFromName(name, comparison, out {Type}{InstanceNullable} result)) return result{Bang};");
            AppendLine($"throw new global::System.ArgumentException(\"'\" + name + \"' is not the name of an instance of {model.TypeName}.\", \"name\");");
            CloseBlock();
            AppendLine();
        }

        private void WriteTryParse()
        {
            if (KeyMember is not ClosedValueMember member)
            {
                return;
            }

            string valueType = ParseValueType(member);
            string result = $"{NotNullWhenTrue}out {Type}{InstanceNullable} result";

            AppendLine($"/// <summary>Finds the instance whose {member.Name} equals <paramref name=\"value\"/>.</summary>");
            AppendLine($"public static bool TryParse({valueType} value, {result})");
            OpenBlock();
            WriteTryParseBody($"global::System.Collections.Generic.EqualityComparer<{member.Type}>.Default.Equals(instance.{Identifier(member.Name)}, value)");
            CloseBlock();
            AppendLine();

            WriteParse(member, valueType, string.Empty, string.Empty);

            if (!member.IsString)
            {
                return;
            }

            AppendLine($"/// <summary>Finds the instance whose {member.Name} equals <paramref name=\"value\"/>, compared with <paramref name=\"comparison\"/>.</summary>");
            AppendLine($"public static bool TryParse({valueType} value, global::System.StringComparison comparison, {result})");
            OpenBlock();
            WriteTryParseBody($"string.Equals(instance.{Identifier(member.Name)}, value, comparison)");
            CloseBlock();
            AppendLine();

            WriteParse(member, valueType, ", global::System.StringComparison comparison", ", comparison");
        }

        private void WriteParse(ClosedValueMember member, string valueType, string extraParameter, string extraArgument)
        {
            string compared = extraParameter.Length > 0 ? ", compared with <paramref name=\"comparison\"/>" : string.Empty;
            AppendLine($"/// <summary>Returns the instance whose {member.Name} equals <paramref name=\"value\"/>{compared}.</summary>");
            AppendLine($"/// <exception cref=\"global::System.ArgumentException\">No instance has the value.</exception>");
            AppendLine($"public static {Type} Parse({valueType} value{extraParameter})");
            OpenBlock();
            AppendLine($"if (TryParse(value{extraArgument}, out {Type}{InstanceNullable} result)) return result{Bang};");
            AppendLine($"throw new global::System.ArgumentException(\"{model.TypeName} has no instance whose {member.Name} is '\" + value + \"'.\", \"value\");");
            CloseBlock();
            AppendLine();
        }

        private void WriteTryParseBody(string condition)
        {
            AppendLine($"foreach ({Type} instance in All)");
            OpenBlock();
            AppendLine($"if ({condition})");
            OpenBlock();
            AppendLine("result = instance;");
            AppendLine("return true;");
            CloseBlock();
            CloseBlock();
            AppendLine();
            AppendLine(model.IsValueType ? "result = default;" : "result = null;");
            AppendLine("return false;");
        }

        private void WriteMatch()
        {
            if (model.Instances.Count == 0)
            {
                return;
            }

            string parameters = string.Join(", ", model.Instances.Select(instance => $"global::System.Func<TResult> {Parameter(instance)}"));
            AppendLine("/// <summary>Calls the function that belongs to this instance. A new instance adds a parameter, so every call site must handle it.</summary>");
            AppendLine($"public TResult Match<TResult>({parameters})");
            OpenBlock();
            foreach (string instance in model.Instances)
            {
                AppendLine($"if ({IsInstance(instance)}) return {Parameter(instance)}();");
            }

            AppendLine($"throw new global::System.InvalidOperationException(\"{model.TypeName} has no instance that matches \" + this + \".\");");
            CloseBlock();
            AppendLine();

            string fallback = Fallback;
            string optional = string.Join(", ", model.Instances.Select(instance => $"global::System.Func<TResult>{Nullable} {Parameter(instance)} = null"));
            AppendLine($"/// <summary>Calls the function that belongs to this instance, or <paramref name=\"{fallback.TrimStart('@')}\"/> when no function is given for it.</summary>");
            AppendLine($"public TResult Match<TResult>(global::System.Func<TResult> {fallback}, {optional})");
            OpenBlock();
            foreach (string instance in model.Instances)
            {
                AppendLine($"if ({IsInstance(instance)}) return ({Parameter(instance)} ?? {fallback})();");
            }

            AppendLine($"return {fallback}();");
            CloseBlock();
            AppendLine();
        }

        /// <summary>
        /// The name of the fallback parameter. It reads like the default arm of a switch. An instance named Default
        /// already has that parameter name, so the fallback becomes a discard, with more underscores as needed.
        /// </summary>
        private string Fallback => FreeParameterName("@default", "_");

        private string FreeParameterName(string preferred, string alternative)
        {
            string name = preferred;
            if (model.Instances.Any(instance => Parameter(instance) == name))
            {
                name = alternative;
                while (model.Instances.Any(instance => Parameter(instance) == name))
                {
                    name = "_" + name;
                }
            }

            return name;
        }

        private void WriteSwitch()
        {
            if (model.Instances.Count == 0)
            {
                return;
            }

            string fallback = Fallback;
            string parameters = string.Join(", ", model.Instances.Select(instance => $"global::System.Action {Parameter(instance)}"));
            AppendLine("/// <summary>Runs the action that belongs to this instance. A new instance adds a parameter, so every call site must handle it.</summary>");
            AppendLine($"public void Switch({parameters})");
            OpenBlock();
            foreach (string instance in model.Instances)
            {
                AppendLine($"if ({IsInstance(instance)}) {{ {Parameter(instance)}(); return; }}");
            }

            AppendLine($"throw new global::System.InvalidOperationException(\"{model.TypeName} has no instance that matches \" + this + \".\");");
            CloseBlock();
            AppendLine();

            string optional = string.Join(", ", model.Instances.Select(instance => $"global::System.Action{Nullable} {Parameter(instance)} = null"));
            AppendLine($"/// <summary>Runs the action that belongs to this instance, or <paramref name=\"{fallback.TrimStart('@')}\"/> when no action is given for it.</summary>");
            AppendLine($"public void Switch(global::System.Action {fallback}, {optional})");
            OpenBlock();
            foreach (string instance in model.Instances)
            {
                AppendLine($"if ({IsInstance(instance)}) {{ ({Parameter(instance)} ?? {fallback})(); return; }}");
            }

            AppendLine($"{fallback}();");
            CloseBlock();
            AppendLine();
        }

        private void WriteMap()
        {
            if (model.Instances.Count == 0)
            {
                return;
            }

            string parameters = string.Join(", ", model.Instances.Select(instance => $"TResult {Parameter(instance)}"));
            AppendLine("/// <summary>Returns the value that belongs to this instance. A new instance adds a parameter, so every call site must handle it.</summary>");
            AppendLine($"public TResult Map<TResult>({parameters})");
            OpenBlock();
            foreach (string instance in model.Instances)
            {
                AppendLine($"if ({IsInstance(instance)}) return {Parameter(instance)};");
            }

            AppendLine($"throw new global::System.InvalidOperationException(\"{model.TypeName} has no instance that matches \" + this + \".\");");
            CloseBlock();
            AppendLine();
        }

        private void WriteMatchWithState()
        {
            if (model.Instances.Count == 0)
            {
                return;
            }

            string state = FreeParameterName("state", "state");
            string parameters = string.Join(", ", model.Instances.Select(instance => $"global::System.Func<TState, TResult> {Parameter(instance)}"));
            AppendLine($"/// <summary>Calls the function that belongs to this instance with <paramref name=\"{state}\"/>, so the functions can be static lambdas without captures.</summary>");
            AppendLine($"public TResult Match<TState, TResult>(TState {state}, {parameters})");
            OpenBlock();
            foreach (string instance in model.Instances)
            {
                AppendLine($"if ({IsInstance(instance)}) return {Parameter(instance)}({state});");
            }

            AppendLine($"throw new global::System.InvalidOperationException(\"{model.TypeName} has no instance that matches \" + this + \".\");");
            CloseBlock();
            AppendLine();
        }

        private string IsInstance(string instance, string subject = "this") =>
            // A class compares references: the instances are the only objects. A struct is a copy, and a record
            // can be copied with 'with', so both compare values.
            model.IsRecord || model.IsValueType
                ? $"{subject}.Equals({Identifier(instance)})"
                : $"object.ReferenceEquals({subject}, {Identifier(instance)})";

        private string BaseList()
        {
            System.Collections.Generic.List<string> interfaces = [];
            if (!model.IsRecord)
            {
                // A record gets its equality and IEquatable<T> from the compiler.
                interfaces.Add($"global::System.IEquatable<{Type}>");
            }

            if (OrderMember is not null)
            {
                interfaces.Add($"global::System.IComparable<{Type}>");
            }

            if (model.WritesParsable)
            {
                interfaces.Add($"global::System.IParsable<{Type}>");
            }

            return interfaces.Count == 0 ? string.Empty : " : " + string.Join(", ", interfaces);
        }

        private void WriteComparison()
        {
            if (OrderMember is not ClosedValueMember member)
            {
                return;
            }

            string compareMembers = $"global::System.Collections.Generic.Comparer<{member.Type}>.Default.Compare(this.{Identifier(member.Name)}, other.{Identifier(member.Name)})";
            AppendLine();
            AppendLine($"/// <summary>Compares the instances by {member.Name}.</summary>");
            AppendLine(model.IsValueType
                ? $"public int CompareTo({Type} other) => {compareMembers};"
                : $"public int CompareTo({Type}{Nullable} other) => other is null ? 1 : {compareMembers};");

            string compare = $"global::System.Collections.Generic.Comparer<{Type}>.Default.Compare(left, right)";
            foreach ((string op, string verb) in new[] { ("<", "is less than"), ("<=", "is less than or equal to"), (">", "is greater than"), (">=", "is greater than or equal to") })
            {
                AppendLine();
                AppendLine($"/// <summary>Returns whether the {member.Name} of <paramref name=\"left\"/> {verb} the one of <paramref name=\"right\"/>.</summary>");
                AppendLine($"public static bool operator {op}({Type}{InstanceNullable} left, {Type}{InstanceNullable} right) => {compare} {op} 0;");
            }
        }

        private void WriteConversions()
        {
            if (KeyMember is not ClosedValueMember member)
            {
                return;
            }

            AppendLine();
            AppendLine($"/// <summary>Returns the {member.Name} of the instance.</summary>");
            if (model.IsValueType)
            {
                AppendLine($"public static implicit operator {member.Type}({Type} value) => value.{Identifier(member.Name)};");
            }
            else
            {
                AppendLine($"public static implicit operator {member.Type}({Type} value)");
                OpenBlock();
                AppendLine("if (value is null) throw new global::System.ArgumentNullException(\"value\");");
                AppendLine($"return value.{Identifier(member.Name)};");
                CloseBlock();
            }

            AppendLine();
            AppendLine($"/// <summary>Returns the instance whose {member.Name} equals <paramref name=\"value\"/>.</summary>");
            AppendLine("/// <exception cref=\"global::System.ArgumentException\">No instance has the value.</exception>");
            AppendLine($"public static explicit operator {Type}({ParseValueType(member)} value) => Parse(value);");
        }

        private void WriteEquality()
        {
            if (model.IsRecord)
            {
                return;
            }

            string memberComparison = string.Join(" && ", model.Members.Select(member =>
                $"global::System.Collections.Generic.EqualityComparer<{member.Type}>.Default.Equals(this.{Identifier(member.Name)}, other.{Identifier(member.Name)})"));

            AppendLine("/// <inheritdoc />");
            AppendLine($"public bool Equals({Type}{InstanceNullable} other)");
            OpenBlock();
            if (model.IsValueType)
            {
                // Every struct without members is the same value.
                AppendLine($"return {(model.Members.Count == 0 ? "true" : memberComparison)};");
            }
            else
            {
                // The instances are the only objects of a class, so an instance equals only itself. A member such as a
                // delegate then takes no part in equality, and Equals agrees with Match.
                AppendLine("return object.ReferenceEquals(this, other);");
            }

            CloseBlock();
            AppendLine();

            AppendLine("/// <inheritdoc />");
            AppendLine(model.IsValueType
                ? $"public override bool Equals(object{Nullable} obj) => obj is {Type} other && Equals(other);"
                : $"public override bool Equals(object{Nullable} obj) => object.ReferenceEquals(this, obj);");
            AppendLine();

            AppendLine("/// <inheritdoc />");
            AppendLine("public override int GetHashCode()");
            OpenBlock();
            if (!model.IsValueType)
            {
                AppendLine("return global::System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode(this);");
            }
            else if (model.Members.Count == 0)
            {
                AppendLine("return 0;");
            }
            else
            {
                AppendLine("unchecked");
                OpenBlock();
                AppendLine("int hash = 17;");
                foreach (ClosedValueMember member in model.Members)
                {
                    AppendLine($"hash = (hash * 31) + global::System.Collections.Generic.EqualityComparer<{member.Type}>.Default.GetHashCode(this.{Identifier(member.Name)}{(model.SupportsNullable ? "!" : string.Empty)});");
                }

                AppendLine("return hash;");
                CloseBlock();
            }

            CloseBlock();
            AppendLine();

            AppendLine("/// <summary>Returns whether both instances are equal.</summary>");
            AppendLine(model.IsValueType
                ? $"public static bool operator ==({Type} left, {Type} right) => left.Equals(right);"
                : $"public static bool operator ==({Type}{Nullable} left, {Type}{Nullable} right) => object.ReferenceEquals(left, right);");
            AppendLine();
            AppendLine("/// <summary>Returns whether both instances differ.</summary>");
            AppendLine($"public static bool operator !=({Type}{InstanceNullable} left, {Type}{InstanceNullable} right) => !(left == right);");
        }

        private void WriteToString()
        {
            ClosedValueMember? text = model.Members.FirstOrDefault(member => member.IsString);
            if (text is null || model.DeclaresToString)
            {
                return;
            }

            if (!model.IsRecord)
            {
                AppendLine();
            }

            AppendLine("/// <inheritdoc />");
            AppendLine($"public override string ToString() => this.{Identifier(text.Name)} ?? string.Empty;");
        }

        /// <summary>
        /// The member that converters write: the single basic member, unless it is an enum. Without it, converters
        /// write the field name of the instance.
        /// </summary>
        private ClosedValueMember? ValueMember => KeyMember is { Kind: not "Enum" } member ? member : null;

        private const string Invariant = "global::System.Globalization.CultureInfo.InvariantCulture";

        private const string TypeDescriptorContext = "global::System.ComponentModel.ITypeDescriptorContext";

        private const string Json = "global::System.Text.Json";

        private void WriteTypeConverter()
        {
            if (!model.Converters.TypeConverter)
            {
                return;
            }

            string notNullWhen = model.SupportsNullable && model.HasNotNullWhenAttribute
                ? "[global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] "
                : string.Empty;
            string form = ValueMember is ClosedValueMember member ? $"the {member.Name}" : "the field name";

            AppendLine();
            AppendLine($"/// <summary>Converts a {model.TypeName} to and from text: {form} of the instance.</summary>");
            AppendLine("public sealed class ClosedValueTypeConverter : global::System.ComponentModel.TypeConverter");
            OpenBlock();
            AppendLine("/// <inheritdoc />");
            AppendLine($"public override bool CanConvertFrom({TypeDescriptorContext}{Nullable} context, global::System.Type sourceType) =>");
            AppendLine("    sourceType == typeof(string) || base.CanConvertFrom(context, sourceType);");
            AppendLine();
            AppendLine("/// <inheritdoc />");
            AppendLine($"public override bool CanConvertTo({TypeDescriptorContext}{Nullable} context, {notNullWhen}global::System.Type{Nullable} destinationType) =>");
            AppendLine("    destinationType == typeof(string) || base.CanConvertTo(context, destinationType);");
            AppendLine();
            AppendLine("/// <inheritdoc />");
            AppendLine($"public override object{Nullable} ConvertFrom({TypeDescriptorContext}{Nullable} context, global::System.Globalization.CultureInfo{Nullable} culture, object value)");
            OpenBlock();
            AppendLine("if (value is string text)");
            OpenBlock();
            AppendLine($"if (FromText(text, out {Type}{InstanceNullable} result)) return result;");
            AppendLine($"throw new global::System.FormatException(\"'\" + text + \"' is not a {model.TypeName}.\");");
            CloseBlock();
            AppendLine();
            AppendLine("return base.ConvertFrom(context, culture, value);");
            CloseBlock();
            AppendLine();
            AppendLine("/// <inheritdoc />");
            AppendLine($"public override object{Nullable} ConvertTo({TypeDescriptorContext}{Nullable} context, global::System.Globalization.CultureInfo{Nullable} culture, object{Nullable} value, global::System.Type destinationType)");
            OpenBlock();
            AppendLine($"if (destinationType == typeof(string) && value is {Type} instance)");
            OpenBlock();
            AppendLine($"string{Nullable} text = ToText(instance);");
            AppendLine("if (text != null) return text;");
            CloseBlock();
            AppendLine();
            AppendLine("return base.ConvertTo(context, culture, value, destinationType);");
            CloseBlock();
            AppendLine();

            AppendLine($"/// <summary>Returns {form} of <paramref name=\"value\"/>, or null when it is no instance.</summary>");
            AppendLine($"internal static string{Nullable} ToText({Type} value)");
            OpenBlock();
            if (ValueMember is ClosedValueMember valueMember)
            {
                string read = $"value.{Identifier(valueMember.Name)}";
                AppendLine(valueMember.Kind switch
                {
                    "String" => $"return {read};",
                    "Char" => $"return {read}.ToString();",
                    "Boolean" => $"return {read} ? \"true\" : \"false\";",
                    "DateTime" => $"return {read}.ToString(\"O\", {Invariant});",
                    _ => $"return {read}.ToString({Invariant});",
                });
            }
            else
            {
                foreach (string instance in model.Instances)
                {
                    AppendLine($"if ({IsInstance(instance, "value")}) return \"{instance}\";");
                }

                AppendLine("return null;");
            }

            CloseBlock();
            AppendLine();

            AppendLine($"/// <summary>Finds the instance whose text, {form}, equals <paramref name=\"text\"/>.</summary>");
            AppendLine($"internal static bool FromText(string{Nullable} text, {NotNullWhenTrue}out {Type}{InstanceNullable} result)");
            OpenBlock();
            if (ValueMember is ClosedValueMember parsedMember)
            {
                string parse = parsedMember.Kind switch
                {
                    "String" => null!,
                    "Char" => "text != null && text.Length == 1",
                    "Boolean" => "bool.TryParse(text, out bool parsed)",
                    "DateTime" => $"{parsedMember.Type}.TryParse(text, {Invariant}, global::System.Globalization.DateTimeStyles.RoundtripKind, out {parsedMember.Type} parsed)",
                    "Single" or "Double" => $"{parsedMember.Type}.TryParse(text, global::System.Globalization.NumberStyles.Float | global::System.Globalization.NumberStyles.AllowThousands, {Invariant}, out {parsedMember.Type} parsed)",
                    "Decimal" => $"{parsedMember.Type}.TryParse(text, global::System.Globalization.NumberStyles.Number, {Invariant}, out {parsedMember.Type} parsed)",
                    _ => $"{parsedMember.Type}.TryParse(text, global::System.Globalization.NumberStyles.Integer, {Invariant}, out {parsedMember.Type} parsed)",
                };

                if (parse is null)
                {
                    AppendLine($"return {Type}.TryParse(text, out result);");
                }
                else
                {
                    string value = parsedMember.Kind == "Char" ? $"text{Bang}[0]" : "parsed";
                    AppendLine($"if ({parse}) return {Type}.TryParse({value}, out result);");
                    AppendLine($"result = {NoInstance};");
                    AppendLine("return false;");
                }
            }
            else
            {
                AppendLine($"return {Type}.TryFromName(text, out result);");
            }

            CloseBlock();
            CloseBlock();
        }

        private void WriteJsonConverter()
        {
            if (!model.WritesJsonConverter)
            {
                return;
            }

            string converter = "ClosedValueTypeConverter";
            string form = ValueMember is ClosedValueMember formMember ? $"the {formMember.Name}" : "the field name";
            string options = $"{Json}.JsonSerializerOptions options";

            AppendLine();
            AppendLine($"/// <summary>Reads and writes a {model.TypeName} as {form} of the instance.</summary>");
            AppendLine($"public sealed class ClosedValueJsonConverter : {Json}.Serialization.JsonConverter<{Type}>");
            OpenBlock();
            AppendLine("/// <inheritdoc />");
            AppendLine($"public override {Type}{InstanceNullable} Read(ref {Json}.Utf8JsonReader reader, global::System.Type typeToConvert, {options})");
            OpenBlock();
            if (ValueMember is ClosedValueMember member)
            {
                if (member.Kind == "Char")
                {
                    AppendLine($"string{Nullable} text = reader.GetString();");
                    AppendLine($"if (text == null || text.Length != 1) throw new {Json}.JsonException(\"Expected a single character for {model.TypeName}.\");");
                    AppendLine("char value = text[0];");
                }
                else
                {
                    string read = member.Kind switch
                    {
                        "String" => "GetString",
                        _ => "Get" + member.Kind,
                    };
                    string valueType = member.Kind == "String" ? "string" + Nullable : member.Type;
                    AppendLine($"{valueType} value = reader.{read}();");
                }

                AppendLine($"if ({Type}.TryParse(value, out {Type}{InstanceNullable} result)) return result;");
                AppendLine($"throw new {Json}.JsonException(\"{model.TypeName} has no instance whose {member.Name} is '\" + value + \"'.\");");
            }
            else
            {
                AppendLine($"string{Nullable} name = reader.GetString();");
                AppendLine($"if ({Type}.TryFromName(name, out {Type}{InstanceNullable} result)) return result;");
                AppendLine($"throw new {Json}.JsonException(\"'\" + name + \"' is not the name of an instance of {model.TypeName}.\");");
            }

            CloseBlock();
            AppendLine();
            AppendLine("/// <inheritdoc />");
            AppendLine($"public override void Write({Json}.Utf8JsonWriter writer, {Type} value, {options})");
            OpenBlock();
            if (ValueMember is ClosedValueMember written)
            {
                string read = $"value.{Identifier(written.Name)}";
                AppendLine(written.Kind switch
                {
                    "String" or "DateTime" => $"writer.WriteStringValue({read});",
                    "Char" => $"writer.WriteStringValue({read}.ToString());",
                    "Boolean" => $"writer.WriteBooleanValue({read});",
                    _ => $"writer.WriteNumberValue({read});",
                });
            }
            else
            {
                AppendLine($"string{Nullable} name = {converter}.ToText(value);");
                AppendLine($"if (name == null) throw new {Json}.JsonException(\"{model.TypeName} has no instance that matches \" + value + \".\");");
                AppendLine("writer.WriteStringValue(name);");
            }

            CloseBlock();

            if (model.Converters.JsonPropertyNames)
            {
                AppendLine();
                AppendLine("/// <inheritdoc />");
                AppendLine($"public override {Type} ReadAsPropertyName(ref {Json}.Utf8JsonReader reader, global::System.Type typeToConvert, {options})");
                OpenBlock();
                AppendLine($"string{Nullable} text = reader.GetString();");
                AppendLine($"if ({converter}.FromText(text, out {Type}{InstanceNullable} result)) return result{Bang};");
                AppendLine($"throw new {Json}.JsonException(\"'\" + text + \"' is not a {model.TypeName}.\");");
                CloseBlock();
                AppendLine();
                AppendLine("/// <inheritdoc />");
                AppendLine($"public override void WriteAsPropertyName({Json}.Utf8JsonWriter writer, {Type} value, {options})");
                OpenBlock();
                AppendLine($"string{Nullable} text = {converter}.ToText(value);");
                AppendLine($"if (text == null) throw new {Json}.JsonException(\"{model.TypeName} has no instance that matches \" + value + \".\");");
                AppendLine("writer.WritePropertyName(text);");
                CloseBlock();
            }

            CloseBlock();
        }

        private void WriteParsable()
        {
            if (!model.WritesParsable)
            {
                return;
            }

            // Public, not explicit: ASP.NET Core minimal APIs bind a parameter through a public static TryParse, and
            // they throw at startup when they find only a non-public one.
            string provider = $"global::System.IFormatProvider{Nullable} provider";
            AppendLine();
            AppendLine("/// <summary>Parses the same text as the type converter: the key, or the field name.</summary>");
            AppendLine("/// <exception cref=\"global::System.FormatException\">No instance has the text.</exception>");
            AppendLine($"public static {Type} Parse(string s, {provider})");
            OpenBlock();
            AppendLine($"if (ClosedValueTypeConverter.FromText(s, out {Type}{InstanceNullable} result)) return result{Bang};");
            AppendLine($"throw new global::System.FormatException(\"'\" + s + \"' is not a {model.TypeName}.\");");
            CloseBlock();
            AppendLine();
            AppendLine("/// <summary>Parses the same text as the type converter: the key, or the field name.</summary>");
            AppendLine($"public static bool TryParse([global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] string{Nullable} s, {provider}, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out {Type} result)");
            OpenBlock();
            AppendLine($"bool found = ClosedValueTypeConverter.FromText(s, out {Type}{InstanceNullable} value);");
            AppendLine($"result = value{Bang};");
            AppendLine("return found;");
            CloseBlock();
        }

        private string Identifier(string name) =>
            SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;

        private string Parameter(string name) =>
            Identifier(char.ToLowerInvariant(name[0]) + name.Substring(1));

        private void OpenBlock()
        {
            AppendLine("{");
            indentation++;
        }

        private void CloseBlock()
        {
            indentation--;
            AppendLine("}");
        }

        private void AppendLine(string line = "")
        {
            if (line.Length > 0)
            {
                builder.Append(' ', indentation * 4);
            }

            builder.Append(line).Append('\n');
        }
    }
